#!/usr/bin/env bash
# Render the trailer from the game itself, frame-locked, from the checked-in shot list.
#
#   tools/trailer.sh                  # every shot, joined -> build/trailer/trailer.mp4
#   tools/trailer.sh --shot choice    # one shot alone     -> build/trailer/shot-choice.mp4
#   tools/trailer.sh --check choice   # render it twice and compare every frame's hash
#   tools/trailer.sh --check all      # the same for every shot
#   tools/trailer.sh --auditions      # one clean capture, then three score mixes
#   tools/trailer.sh --list           # print the shot list and render nothing
#
# PLAYTEST-139: "we can use recordings from a frame locked game. the trailer will be a set of
# paths in pre determined seeds with fixed events so we can reproduce it easily" · "we need to be
# careful not to directly check in either the images or the video so it should be possible to
# run by me and I can generate the video myself. so the setting scripts need to produce the same
# output every time."
#
# Each shot in tools/trailer/shots.json is one Godot launch through its own movie writer
# (`--write-movie <tmp>/frame.png --fixed-fps <fps>`): the game runs frame-locked -- every frame
# advances the clock by exactly 1/fps however long it takes to draw and save -- and writes one PNG
# per frame plus `frame.wav`, the game's own audio mixed at the same clock. The shot's cut is
# taken out of those frames, faded in and out of black and encoded, and the frames are deleted
# before the next shot starts. Editorial cards, end copy and the original oscillator score are
# generated by ffmpeg from the same checked-in shot list; captured game audio stays audible under
# that score. The shots are then joined into one H.264/AAC file. Everything this
# writes is under build/ (gitignored) or a temporary directory it removes, and it fails, naming the
# paths, if the working tree's own status changed while it ran.
#
# The window opens at the game's own resolution (project.godot's viewport size), takes no focus
# and hears no stray key: the movie writer (`--write-movie`) makes DevFlags.recording() true, which
# is itself one of is_rig()'s conditions, so the game's M195 lockdown applies without any dev flag
# of its own, and the same focus guard tools/shot.sh uses hands focus straight back. Every shot also
# carries `--player-view`, so the frame is the release build's own HUD with the debug readout off
# rather than a rig's, and `--no-focus-pause`, since a window that never has real OS focus in the
# first place would otherwise open the pause screen on its own first frame and every frame shows
# that instead of the day it was sent to render. A shot is killed from outside if it outlives the
# movie writer's own deadline
# (see rig_kill_after_movie_seconds in tools/lib_dev_flags.sh).
set -euo pipefail

GODOT="${GODOT:-/Applications/Godot.app/Contents/MacOS/Godot}"
PROJECT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SHOTS_FILE="${TRAILER_SHOTS:-$PROJECT_DIR/tools/trailer/shots.json}"
SCORES_FILE="${TRAILER_SCORES:-$PROJECT_DIR/tools/trailer/scores.json}"
OUT_DIR="${TRAILER_OUT:-$PROJECT_DIR/build/trailer}"
# shellcheck source=tools/lib_dev_flags.sh
source "$PROJECT_DIR/tools/lib_dev_flags.sh"
# shellcheck source=tools/lib_movie_evidence.sh
source "$PROJECT_DIR/tools/lib_movie_evidence.sh"
# shellcheck source=tools/lib_disk_headroom.sh
source "$PROJECT_DIR/tools/lib_disk_headroom.sh"

usage() {
    cat <<EOF
usage: tools/trailer.sh [--help|-h] [--list | --validate | --auditions | --shot NAME | --check NAME|all | --check-load NAME|all]

Renders the trailer from tools/trailer/shots.json: gameplay shots through Godot's movie writer,
frame-locked, at the game's own resolution with its audio; editorial cards and the deterministic
oscillator score through ffmpeg; then fades, mixes, joins and encodes them. Frames are deleted as
soon as each shot is encoded. Output goes to TRAILER_OUT (default: build/trailer/, gitignored).

  (no flag)        render every shot and join them into TRAILER_OUT/trailer.mp4
  --auditions      capture one clean game-audio base, then build three complete score mixes in
                   TRAILER_OUT; a matching retained base is reused on later score-only runs
  --shot NAME      render one shot alone into TRAILER_OUT/shot-NAME.mp4
  --check NAME     render the shot twice and compare every frame's hash; exits non-zero on a
                   difference inside the shot's cut
  --check all      the same for every shot in the list
  --check-load NAME|all  compare an ordinary render with one under a CPU load worker
  --validate       headlessly validate every recipe; never open a recording window
  --list           print the shot list (name, kind, source, length, gap); render nothing

Environment:
  TRAILER_SHOTS    use another shot-list JSON (default: tools/trailer/shots.json)
  TRAILER_SCORES   use another score-list JSON (default: tools/trailer/scores.json)
  TRAILER_OUT      output directory (default: build/trailer)

Disk: frames stay on disk until each shot is encoded, so this refuses to start unless the volume
holding \$TMPDIR has the record-second estimate (tools/lib_disk_headroom.sh) free for every game
second of the shots asked for (an upper bound, as only one shot's frames exist at a time), and warns
when that leaves less than the reserve. A stale atlas repair is checked the same way.

Checks retain hashes, manifests and settings in TRAILER_OUT/checks/. Simulation observations
and audio must match too; editorial cards compare decoded frame and silence hashes. Equality applies only to
the recorded engine, assets, ffmpeg/font, and settings named by the retained manifests.

  tools/trailer.sh --shot choice

Opens a window for each gameplay shot. Needs jq, ffmpeg and fc-match on PATH, and Godot 4.7 at \$GODOT.
EOF
}

MODE="all"
TARGET=""
while [[ $# -gt 0 ]]; do
    case "$1" in
        --help|-h) usage; exit 0 ;;
        --list|--validate|--auditions)
            [[ "$MODE" == "all" ]] || { echo "$1 cannot be combined with --$MODE" >&2; usage >&2; exit 1; }
            MODE="${1#--}"; shift ;;
        --shot|--check|--check-load)
            [[ "$MODE" == "all" ]] || { echo "$1 cannot be combined with --$MODE" >&2; usage >&2; exit 1; }
            if [[ $# -lt 2 || "$2" == --* ]]; then
                echo "$1 is missing its shot name" >&2; echo >&2; usage >&2; exit 1
            fi
            MODE="${1#--}"; TARGET="$2"; shift 2 ;;
        *)
            echo "unrecognized argument: $1" >&2; echo >&2; usage >&2; exit 1 ;;
    esac
done

for tool in jq; do
    if ! command -v "$tool" >/dev/null 2>&1; then
        echo "trailer.sh: $tool not found on PATH" >&2
        exit 127
    fi
done
if [[ ! -f "$SHOTS_FILE" ]]; then
    echo "trailer.sh: no shot list at ${SHOTS_FILE#"$PROJECT_DIR"/}" >&2
    exit 1
fi
if [[ "$MODE" == auditions && ! -f "$SCORES_FILE" ]]; then
    echo "trailer.sh: no audition score list at ${SCORES_FILE#"$PROJECT_DIR"/}" >&2
    exit 1
fi

# ------------------------------------------------------------------- the shot list, checked ---
# Every shot is checked before any window opens: the fields a shot must carry, the dev flags it
# forwards (against the game's own DEV_FLAG_TABLE, the same way run.sh and shot.sh check theirs),
# and the editorial fields. The cut has no length cap.
schema_errors="$(jq -r '
    def num: type == "number";
    (if (keys - ["fps","fade","style","score","shots"] | length) == 0
        then empty else "unknown top-level field" end),
    (if (.fps | num) and .fps > 0 and .fps == (.fps | floor) then empty
        else "fps must be a positive integer" end),
    (if (.shots | type) == "array" and (.shots | length) > 0 then empty
        else "shots must be a non-empty array" end),
    (if (.style | type) == "object" and
        (.style | keys - ["font_family","card_background","paper","ink","accent"] | length) == 0 and
        all([.style.font_family,.style.card_background,.style.paper,.style.ink,.style.accent][];
            type == "string" and length > 0)
        then empty else "style must name the font and three colors" end),
    (if (.score | type) == "object" and
        (.score | keys - ["game_gain","notes"] | length) == 0 and
        (.score.game_gain | num) and .score.game_gain >= 0 and .score.game_gain <= 1 and
        (.score.notes | type) == "array" and (.score.notes | length) > 0 and
        all(.score.notes[];
            (keys - ["at","duration","frequency","gain"] | length) == 0 and
            (.at | num) and .at >= 0 and (.duration | num) and .duration > 0 and
            (.frequency | num) and .frequency > 0 and (.gain | num) and .gain > 0 and .gain <= 0.25)
        then empty else "score must contain bounded deterministic notes and a game_gain" end),
    ((.shots // [])[] |
        (.name // "?") as $n |
        (.kind // "scene") as $kind |
        (if (.name | type) == "string" and (.name | test("^[a-z0-9-]+$")) then empty
            else "a shot name must be lower-case letters, digits and dashes: \($n)" end),
        (if $kind == "scene" or $kind == "card" then empty
            else "\($n): kind must be scene or card" end),
        (if $kind == "scene" and (.recipe | type) == "string" and
                (.recipe | test("^scene-recipes/[a-z0-9-]+\\.json$")) and (.card == null)
            then empty
            elif $kind == "card" and (.recipe == null) and (.in == null) and
                (.card | type) == "object" and
                (.card | keys - ["text","font_size","subtitle","subtitle_font_size","asset","layout","illustration","frame","animation"] | length) == 0 and
                (((.card.asset | type) == "string" and (.card.asset | test("^art/[a-z0-9/_-]+\\.png$")) and
                    .card.text == null and .card.font_size == null and .card.subtitle == null and
                    .card.subtitle_font_size == null and .card.layout == null and .card.illustration == null and
                    .card.frame == null and .card.animation == null) or
                 ((.card.text | type) == "string" and (.card.text | length) > 0 and
                    (.card.font_size | num) and .card.font_size > 0 and .card.asset == null and
                    ((.card.layout == null and .card.illustration == null and .card.frame == null and
                      .card.animation == null) or
                     (.card.layout == "split" and (.card.illustration | type) == "string" and
                      (.card.illustration | test("^art/[a-z0-9/_-]+\\.png$")) and
                      .card.frame == null and .card.animation == null) or
                     (.card.layout == "window" and .card.illustration == null and
                      (.card.frame | type) == "string" and
                      (.card.frame | test("^tools/trailer/window/[a-z0-9-]+\\.png$")) and
                      (.card.animation | type) == "array" and (.card.animation | length) == 3 and
                      all(.card.animation[];
                        type == "string" and test("^tools/trailer/window/[a-z0-9-]+\\.png$")))) and
                    ((.card.subtitle == null and .card.subtitle_font_size == null) or
                     ((.card.subtitle | type) == "string" and (.card.subtitle | length) > 0 and
                      (.card.subtitle_font_size | num) and .card.subtitle_font_size > 0))))
            then empty
            else "\($n): scene shots need a recipe; card shots need text and font_size" end),
        (if (keys - ["name","kind","recipe","card","ending","captions","motion","length","in","gap","fade_in","fade_out"] | length) == 0
            then empty else "\($n): unknown shot field (setup and playback belong in the recipe)" end),
        (if .motion == null or (.motion | type) == "boolean" then empty
            else "\($n): motion must be true or false" end),
        (if .captions == null then empty
            elif $kind == "scene" and (.captions | type) == "array" and (.captions | length) > 0 and
                all(.captions[]; (keys - ["at","until","text","font_size"] | length) == 0 and
                    (.at | num) and .at >= 0 and (.until | num) and .until > .at and
                    (.text | type) == "string" and (.text | length) > 0 and
                    (.font_size | num) and .font_size > 0)
            then empty else "\($n): captions are malformed or belong to a card" end),
        (if .ending == null then empty
            elif $kind == "scene" and (.ending | type) == "object" and
                (.ending | keys - ["at","line","url","line_font_size","url_font_size"] | length) == 0 and
                (.ending.at | num) and .ending.at >= 0 and
                all([.ending.line,.ending.url][]; type == "string" and length > 0) and
                all([.ending.line_font_size,.ending.url_font_size][]; num and . > 0)
            then empty else "\($n): ending copy is malformed or belongs to a card" end),
        (if (.length | num) and .length > 0 then empty else "\($n): length must be positive" end),
        (if (.in // 0 | num) and (.in // 0) >= 0 then empty else "\($n): in must be >= 0" end),
        (if (.gap // 0 | num) and (.gap // 0) >= 0 then empty else "\($n): gap must be >= 0" end),
        (if all([(.fade_in // 0.25),(.fade_out // 0.25)][]; num and . >= 0) then empty
            else "\($n): fades must be nonnegative numbers" end)
    ),
    (if ([.shots[]?.name] | length) == ([.shots[]?.name] | unique | length) then empty
        else "two shots share a name" end)
' "$SHOTS_FILE" 2>&1)" || { echo "trailer.sh: ${SHOTS_FILE#"$PROJECT_DIR"/} is not valid JSON" >&2; exit 1; }
if [[ -n "$schema_errors" ]]; then
    echo "trailer.sh: ${SHOTS_FILE#"$PROJECT_DIR"/} is malformed:" >&2
    printf '  %s\n' "$schema_errors" >&2
    exit 1
fi

if [[ "$MODE" == auditions ]]; then
    score_errors="$(jq -r '
        def num: type == "number";
        (if (keys - ["game_gain","target_mean_db","peak_ceiling_db","options"] | length) == 0
            then empty else "unknown top-level score field" end),
        (if (.game_gain | num) and .game_gain >= 0 and .game_gain <= 1 then empty
            else "game_gain must be between zero and one" end),
        (if (.target_mean_db | num) and .target_mean_db >= -60 and .target_mean_db <= -18
            then empty else "target_mean_db must be between -60 and -18" end),
        (if (.peak_ceiling_db | num) and .peak_ceiling_db >= -24 and .peak_ceiling_db <= -3
            then empty else "peak_ceiling_db must be between -24 and -3" end),
        (if (.options | type) == "array" and (.options | length) == 3 then empty
            else "options must contain exactly three scores" end),
        ((.options // [])[] |
            (.id // "?") as $id |
            (if (keys - ["id","label","description","events"] | length) == 0
                then empty else "\($id): unknown option field" end),
            (if (.id | type) == "string" and (.id | test("^[a-z0-9-]+$"))
                then empty else "an option id must use lower-case letters and dashes" end),
            (if all([.label,.description][]; type == "string" and length > 0)
                then empty else "\($id): label and description are required" end),
            (if (.events | type) == "array" and (.events | length) > 0 and all(.events[];
                (keys - ["shot","offset","duration","frequency","gain","texture"] | length) == 0 and
                (.shot | type) == "string" and (.offset | num) and .offset >= 0 and
                (.duration | num) and .duration > 0 and (.frequency | num) and .frequency > 0 and
                (.gain | num) and .gain > 0 and .gain <= 1 and
                (.texture | IN("pluck","glass","pulse","drone","tick")))
                then empty else "\($id): events are malformed" end)
        ),
        (if ([.options[]?.id] | length) == ([.options[]?.id] | unique | length)
            then empty else "two score options share an id" end)
    ' "$SCORES_FILE" 2>&1)" || {
        echo "trailer.sh: ${SCORES_FILE#"$PROJECT_DIR"/} is not valid JSON" >&2; exit 1;
    }
    if [[ -n "$score_errors" ]]; then
        echo "trailer.sh: ${SCORES_FILE#"$PROJECT_DIR"/} is malformed:" >&2
        printf '  %s\n' "$score_errors" >&2
        exit 1
    fi
fi

FPS="$(jq -r '.fps' "$SHOTS_FILE")"
DEFAULT_FADE="$(jq -r '.fade // 0.25' "$SHOTS_FILE")"
SHOT_NAMES=()
while IFS= read -r name; do SHOT_NAMES+=("$name"); done < <(jq -r '.shots[].name' "$SHOTS_FILE")

# One field of one shot, or $3 when the shot does not carry it.
shot_field() {
    jq -r --arg n "$1" --arg f "$2" --arg d "${3:-}" \
        '.shots[] | select(.name == $n) | (.[$f] // $d) | tostring' "$SHOTS_FILE"
}

shot_kind() {
    shot_field "$1" kind scene
}

shot_nested_field() {
    jq -r --arg n "$1" --arg o "$2" --arg f "$3" \
        '.shots[] | select(.name == $n) | .[$o][$f] | tostring' "$SHOTS_FILE"
}

# The recipe owns scene setup and playback; the shot only selects the capture deadline.
shot_game_flags() {
    [[ "$(shot_kind "$1")" == scene ]] || return 0
    printf '%s\n' --player-view --no-save --no-focus-pause \
        --recipe "$PROJECT_DIR/$(shot_field "$1" recipe)" --recipe-mode scripted \
        --after "$(shot_render_seconds "$1")"
}

# Run every authored assertion, even when the selected cut ends before the scene does.
shot_render_seconds() {
    local duration
    duration="$(jq -r '.playback.duration // 5' "$PROJECT_DIR/$(shot_field "$1" recipe)")"
    awk -v a="$(shot_field "$1" in 0.5)" -v b="$(shot_field "$1" length)" \
        -v duration="$duration" 'BEGIN { end=a+b; printf "%.3f\n", (end>duration ? end : duration) }'
}

total_seconds="$(jq -r '[.shots[] | (.gap // 0) + .length] | add' "$SHOTS_FILE" |
    awk '{ printf "%.2f\n", $1 }')"
RESOLVED_SCORES=""
if [[ "$MODE" == auditions ]]; then
    RESOLVED_SCORES="$(jq -n --slurpfile cut "$SHOTS_FILE" --slurpfile scores "$SCORES_FILE" '
        (reduce $cut[0].shots[] as $shot ({elapsed:0,starts:{}};
            .starts[$shot.name] = (.elapsed + ($shot.gap // 0)) |
            .elapsed += (($shot.gap // 0) + $shot.length))) as $timeline |
        $scores[0] + {
            total_seconds:$timeline.elapsed,
            military_start:$timeline.starts.trucks,
            options: [$scores[0].options[] |
                . + {events: [.events[] |
                    . + {at: ($timeline.starts[.shot] + .offset)}]}]
        }
    ')"
    if ! jq -e --argjson total "$total_seconds" '
        ((.total_seconds - $total) | fabs) < 0.001 and
        all(.options[].events[]; (.at | type) == "number" and .at + .duration <= $total + 0.001)
    ' <<< "$RESOLVED_SCORES" >/dev/null; then
        echo "trailer.sh: an audition cue names no shot or finishes outside the cut" >&2
        exit 1
    fi
fi
if ! jq -e --argjson total "$total_seconds" '
    all(.score.notes[]; .at + .duration <= $total) and
    all(.shots[] | select(.ending != null); .ending.at < .length) and
    all(.shots[] | select(.captions != null); .length as $l | all(.captions[]; .until <= $l))
' "$SHOTS_FILE" >/dev/null; then
    echo "trailer.sh: score notes and ending copy must finish inside the cut" >&2
    exit 1
fi

for name in "${SHOT_NAMES[@]}"; do
    [[ "$(shot_kind "$name")" == scene ]] || continue
    flags=()
    while IFS= read -r word; do flags+=("$word"); done < <(shot_game_flags "$name")
    if ! validate_dev_flags "${flags[@]}"; then
        echo "trailer.sh: shot '$name' forwards a flag the game does not know (see above)" >&2
        exit 1
    fi
done

if [[ "$MODE" == "shot" || "$MODE" == "check" || "$MODE" == "check-load" ]] && [[ "$TARGET" != "all" || "$MODE" == "shot" ]]; then
    found=""
    for name in "${SHOT_NAMES[@]}"; do [[ "$name" == "$TARGET" ]] && found=1; done
    if [[ -z "$found" ]]; then
        echo "trailer.sh: no shot named '$TARGET' in the list (${SHOT_NAMES[*]})" >&2
        exit 1
    fi
fi

if [[ "$MODE" == "list" ]]; then
    printf '%-10s %-10s %-40s %6s %5s\n' shot kind source length gap
    for name in "${SHOT_NAMES[@]}"; do
        source="$(shot_field "$name" recipe '[editorial card]')"
        printf '%-10s %-10s %-40s %6s %5s\n' "$name" "$(shot_kind "$name")" "$source" \
            "$(shot_field "$name" length)" "$(shot_field "$name" gap 0)"
    done
    echo "total ${total_seconds}s"
    exit 0
fi

# `--validate` renders nothing, so it needs neither ffmpeg nor a font; every other mode does.
if [[ "$MODE" != validate ]]; then
    for tool in ffmpeg fc-match; do
        if ! command -v "$tool" >/dev/null 2>&1; then
            echo "trailer.sh: $tool not found on PATH" >&2
            exit 127
        fi
    done
fi

if [[ ! -x "$GODOT" ]]; then
    echo "godot not found at $GODOT" >&2
    echo "install Godot 4.7, or point GODOT at your binary:" >&2
    echo "  GODOT=/path/to/Godot tools/trailer.sh" >&2
    exit 127
fi

# The game's own resolution, read where the game declares it.
WIDTH="$(sed -n 's/^window\/size\/viewport_width=//p' "$PROJECT_DIR/project.godot")"
HEIGHT="$(sed -n 's/^window\/size\/viewport_height=//p' "$PROJECT_DIR/project.godot")"
if ! [[ "$WIDTH" =~ ^[0-9]+$ && "$HEIGHT" =~ ^[0-9]+$ ]]; then
    echo "trailer.sh: could not read the viewport size from project.godot" >&2
    exit 1
fi

FONT_FAMILY="$(jq -r '.style.font_family' "$SHOTS_FILE")"
FONT_FILE=""
if [[ "$MODE" != validate ]]; then
    # A font that does not resolve to the family asked for stops the render: `fc-match` answers
    # with its nearest substitute rather than failing, and a trailer set in a substitute is the
    # wrong trailer.
    FONT_FILE="$(fc-match -f '%{file}\n' "$FONT_FAMILY" | head -1)"
    FONT_RESOLVED="$(fc-match -f '%{family}\n' "$FONT_FAMILY" | head -1)"
    if [[ -z "$FONT_FILE" || ! -f "$FONT_FILE" ]]; then
        echo "trailer.sh: fontconfig could not resolve the editorial font '$FONT_FAMILY'" >&2
        exit 1
    fi
    if ! printf '%s\n' "$FONT_RESOLVED" | tr ',' '\n' | grep -Fixq -- "$FONT_FAMILY"; then
        echo "trailer.sh: the editorial font '$FONT_FAMILY' resolved to '$FONT_RESOLVED' ($FONT_FILE), not the family asked for" >&2
        exit 1
    fi
fi
if [[ -n "$FONT_FILE" && ( "$FONT_FILE" == *":"* || "$FONT_FILE" == *"'"* ) ]]; then
    echo "trailer.sh: the resolved editorial font path cannot be passed safely to ffmpeg: $FONT_FILE" >&2
    exit 1
fi
PAPER="$(jq -r '.style.paper' "$SHOTS_FILE")"
INK="$(jq -r '.style.ink' "$SHOTS_FILE")"
ACCENT="$(jq -r '.style.accent' "$SHOTS_FILE")"
CARD_BACKGROUND="$(jq -r '.style.card_background' "$SHOTS_FILE")"

while IFS= read -r asset; do
    if [[ ! -f "$PROJECT_DIR/$asset" ]] || ! git -C "$PROJECT_DIR" ls-files --error-unmatch "$asset" >/dev/null 2>&1; then
        echo "trailer.sh: editorial card asset is absent or untracked: $asset" >&2
        exit 1
    fi
done < <(jq -r '.shots[].card | (.asset? // empty), (.illustration? // empty),
    (.frame? // empty), (.animation[]? // empty)' "$SHOTS_FILE")

# The baked atlas pages, repaired the way tools/shot.sh repairs them -- see its own comment.
if ! "$PROJECT_DIR/tools/bake-atlases.sh" --check >/dev/null 2>&1; then
    "$PROJECT_DIR/tools/bake-atlases.sh" --check >&2 || true
    headroom_preflight tools/trailer.sh "$PROJECT_DIR/.godot" "" import || exit 1
    echo "rebuilding with tools/check.sh -- this takes a few seconds" >&2
    if ! "$PROJECT_DIR/tools/check.sh" >/dev/null; then
        echo "tools/check.sh failed; run it directly to see why" >&2
        exit 1
    fi
fi

# ------------------------------------------------------------------------------ rendering ---
WORK="$(mktemp -d "${TMPDIR:-/tmp}/nappy-trailer.XXXXXX")"
FOCUS_WATCHER_PID=""
LOAD_PID=""
cleanup() {
    [[ -z "$LOAD_PID" ]] || kill "$LOAD_PID" 2>/dev/null || true
    rig_focus_watch_stop "$FOCUS_WATCHER_PID"
    rm -rf "$WORK"
}
trap cleanup EXIT

TREE_BEFORE="$(git -C "$PROJECT_DIR" status --porcelain 2>/dev/null || true)"

# Validate the game's resolved normal classification before opening any movie window.
targets=("${SHOT_NAMES[@]}")
[[ -z "$TARGET" || "$TARGET" == all ]] || targets=("$TARGET")
mkdir -p "$WORK/preflight"
recipe_count=0
for name in "${targets[@]}"; do
    [[ "$(shot_kind "$name")" == scene ]] || continue
    recipe="$(shot_field "$name" recipe)"
    if [[ ! -f "$PROJECT_DIR/$recipe" ]] || ! git -C "$PROJECT_DIR" ls-files --error-unmatch "$recipe" >/dev/null 2>&1; then
        echo "trailer.sh: recipe is absent or untracked: $recipe" >&2; exit 1
    fi
    movie_recipe_preflight "$PROJECT_DIR/$recipe" "$WORK/preflight/$name.json" true scripted
    recipe_count=$(( recipe_count + 1 ))
done
if [[ "$MODE" == validate ]]; then
    mkdir -p "$OUT_DIR/validation"
    cp "$WORK/preflight/"*.json "$OUT_DIR/validation/"
    echo "validated ${recipe_count} normal scene recipes and the editorial configuration"
    exit 0
fi

# The whole render is the batch, checked before the first movie window opens. A shot's frames are
# deleted once it is encoded, so the peak is the largest shot's, but the estimate charges the
# summed render seconds of every shot asked for -- an upper bound, like every estimate in
# tools/lib_disk_headroom.sh -- at its record-second rate. Validation writes no frames.
render_seconds_total="$(for name in "${targets[@]}"; do
    [[ "$(shot_kind "$name")" == scene ]] || continue
    shot_render_seconds "$name"
done |
    awk '{ s += $1 } END { printf "%d\n", (s == int(s)) ? s : int(s) + 1 }')"
if [[ "$render_seconds_total" -gt 0 ]]; then
    headroom_preflight tools/trailer.sh "$WORK" \
        "render fewer shots: --shot NAME renders one, and the shot list's lengths set the rest" \
        "record-second:$render_seconds_total" || exit 1
fi

# Renders shot $1's frames and audio into directory $2 (created empty). Fails loudly if Godot
# did not quit on its own or did not write the frames the cut needs.
render_frames() {
    local name="$1" dir="$2" after kill_after flags=()
    rm -rf "$dir"; mkdir -p "$dir"
    while IFS= read -r word; do flags+=("$word"); done < <(shot_game_flags "$name")
    flags+=(--recipe-manifest "$dir/manifest.json")
    after="$(shot_render_seconds "$name")"
    kill_after="$(rig_kill_after_movie_seconds --after "$after")"
    echo "rendering '$name' (${after}s of game at ${FPS}fps)..." >&2
    local noted
    noted="$(rig_focus_note)"
    "$GODOT" --path "$PROJECT_DIR" --resolution "${WIDTH}x${HEIGHT}" --disable-vsync \
        --write-movie "$dir/frame.png" --fixed-fps "$FPS" \
        -- "${flags[@]}" > "$dir/godot.log" 2>&1 &
    local pid=$!
    FOCUS_WATCHER_PID="$(rig_focus_watch_start "$pid" "$noted")"
    if ! wait_or_kill "$pid" "$kill_after"; then
        rig_focus_watch_stop "$FOCUS_WATCHER_PID"; FOCUS_WATCHER_PID=""
        echo "trailer.sh: killed Godot after ${kill_after}s rendering '$name' -- it did not quit" >&2
        tail -20 "$dir/godot.log" >&2
        return 1
    fi
    rig_focus_watch_stop "$FOCUS_WATCHER_PID"; FOCUS_WATCHER_PID=""
    if [[ "$WAIT_OR_KILL_STATUS" -ne 0 ]]; then
        echo "trailer.sh: Godot exited $WAIT_OR_KILL_STATUS rendering '$name'" >&2
        tail -20 "$dir/godot.log" >&2
        return 1
    fi
    if grep -qE '^(SCRIPT )?ERROR' "$dir/godot.log"; then
        echo "trailer.sh: '$name' printed an engine error while rendering:" >&2
        grep -E -A2 '^(SCRIPT )?ERROR' "$dir/godot.log" | head -20 >&2
        return 1
    fi
    movie_manifest_check "$dir/manifest.json" true || return 1
    movie_playback_check "$dir/manifest.json" || return 1
    local need last
    need="$(awk -v a="$(shot_field "$name" in 0.5)" -v b="$(shot_field "$name" length)" \
        -v f="$FPS" 'BEGIN { printf "%d\n", int((a + b) * f + 0.5) }')"
    last="$(printf '%s/frame%08d.png' "$dir" "$((need - 1))")"
    if [[ ! -f "$last" ]]; then
        echo "trailer.sh: '$name' wrote too few frames (no $(basename "$last"))" >&2
        return 1
    fi
    visible_motion_check "$name" "$dir"
}

# A manifest proves that the recipe advanced; this proves that the selected pixels did too. The
# half-second ceiling permits a deliberate held pose while rejecting the stale viewport texture a
# covered macOS movie-writer window otherwise repeats for the rest of a live scene.
visible_motion_check() {
    local name="$1" dir="$2"
    [[ "$(shot_field "$name" motion false)" == true ]] || return 0
    local start count end frame file hash previous="" run=0 longest=0
    start="$(awk -v a="$(shot_field "$name" in 0.5)" -v f="$FPS" \
        'BEGIN { printf "%d\n", int(a * f + 0.5) }')"
    count="$(awk -v a="$(shot_field "$name" length)" -v f="$FPS" \
        'BEGIN { printf "%d\n", int(a * f + 0.5) }')"
    end=$(( start + count ))
    for (( frame=start; frame<end; frame++ )); do
        file="$(printf '%s/frame%08d.png' "$dir" "$frame")"
        hash="$(shasum -a 256 < "$file" | awk '{print $1}')"
        if [[ "$hash" == "$previous" ]]; then
            run=$(( run + 1 ))
        else
            run=1
            previous="$hash"
        fi
        (( run > longest )) && longest="$run"
    done
    if (( longest > FPS / 2 )); then
        echo "trailer.sh: '$name' has $longest consecutive identical selected frames; its visible motion froze" >&2
        return 1
    fi
}

# Keeps five native frames around the retained cut's first frame. A post-fade contact sheet can show
# that an entrance looks smooth, but only these excluded-lead-in frames prove the actor and camera
# had already settled before the editor began the shot. The build directory is ignored; source
# control never receives these captures.
write_cut_entry_evidence() {
    local name="$1" dir="$2" out="$OUT_DIR/evidence/$name/cut-entry"
    local start frame i=0 last_path last_frame actual_offset actual_seconds clamped
    local fifth second_fifth one_frame_seconds
    start="$(awk -v a="$(shot_field "$name" in 0.5)" -v f="$FPS" \
        'BEGIN { printf "%d\n", int(a * f + 0.5) }')"
    fifth="$(awk -v f="$FPS" 'BEGIN { printf "%d\n", int(0.2 * f + 0.5) }')"
    second_fifth="$(awk -v f="$FPS" 'BEGIN { printf "%d\n", int(0.4 * f + 0.5) }')"
    one_frame_seconds="$(awk -v f="$FPS" 'BEGIN { printf "%.9f\n", -1 / f }')"
    local offsets=($((-fifth)) -1 0 "$fifth" "$second_fifth")
    local requested_seconds=(-0.2 "$one_frame_seconds" 0 0.2 0.4)
    last_path="$(printf '%s\n' "$dir"/frame*.png | tail -1)"
    last_frame="${last_path##*frame}"; last_frame="${last_frame%.png}"
    last_frame=$(( 10#$last_frame ))
    rm -rf "$out"; mkdir -p "$out"
    for offset in "${offsets[@]}"; do
        frame=$(( start + offset ))
        clamped=false
        if (( frame < 0 )); then frame=0; clamped=true; fi
        if (( frame > last_frame )); then frame="$last_frame"; clamped=true; fi
        actual_offset=$(( frame - start ))
        actual_seconds="$(awk -v n="$actual_offset" -v f="$FPS" \
            'BEGIN { printf "%.9f\n", n / f }')"
        cp "$(printf '%s/frame%08d.png' "$dir" "$frame")" "$out/sample-$i.png"
        jq -nc --arg file "sample-$i.png" --argjson requested_seconds "${requested_seconds[$i]}" \
            --argjson requested_frames "$offset" --argjson source_frame "$frame" \
            --argjson actual_frames "$actual_offset" --argjson actual_seconds "$actual_seconds" \
            --argjson clamped "$clamped" \
            '{file:$file,requested_offset_seconds:$requested_seconds,
              requested_offset_frames:$requested_frames,source_frame:$source_frame,
              actual_offset_frames:$actual_frames,actual_offset_seconds:$actual_seconds,
              clamped:$clamped}' >> "$out/samples.jsonl"
        i=$(( i + 1 ))
    done
    jq -s --arg name "$name" --argjson fps "$FPS" --argjson retained_frame "$start" \
        '{shot:$name,fps:$fps,retained_frame:$retained_frame,samples:.}' \
        "$out/samples.jsonl" > "$out/index.json"
    rm "$out/samples.jsonl"
    ffmpeg -hide_banner -loglevel error -y \
        -i "$out/sample-0.png" -i "$out/sample-1.png" -i "$out/sample-2.png" \
        -i "$out/sample-3.png" -i "$out/sample-4.png" \
        -filter_complex \
        '[0:v]scale=256:144[a];[1:v]scale=256:144[b];[2:v]scale=256:144[c];[3:v]scale=256:144[d];[4:v]scale=256:144[e];[a][b][c][d][e]hstack=inputs=5[v]' \
        -map '[v]' -frames:v 1 "$out/contact-sheet.png"
}

# Encodes shot $1's cut out of the frames in $2 into $3: trimmed to [in, in + length], faded in
# from and out to black, preceded by `gap` seconds of black and silence.
encode_shot() {
    local name="$1" dir="$2" out="$3"
    local in length gap fade_in fade_out start count
    in="$(shot_field "$name" in 0.5)"
    length="$(shot_field "$name" length)"
    gap="$(shot_field "$name" gap 0)"
    fade_in="$(shot_field "$name" fade_in "$DEFAULT_FADE")"
    fade_out="$(shot_field "$name" fade_out "$DEFAULT_FADE")"
    start="$(awk -v a="$in" -v f="$FPS" 'BEGIN { printf "%d\n", int(a * f + 0.5) }')"
    count="$(awk -v a="$length" -v f="$FPS" 'BEGIN { printf "%d\n", int(a * f + 0.5) }')"
    local out_start total
    out_start="$(awk -v l="$length" -v o="$fade_out" 'BEGIN { printf "%.4f\n", l - o }')"
    total="$(awk -v l="$length" -v g="$gap" 'BEGIN { printf "%.4f\n", l + g }')"
    local audio=(-f lavfi -i "anullsrc=r=48000:cl=stereo")
    [[ -f "$dir/frame.wav" ]] && audio=(-i "$dir/frame.wav")
    local gap_ms
    gap_ms="$(awk -v g="$gap" 'BEGIN { printf "%d\n", int(g * 1000 + 0.5) }')"
    local video_filters="trim=end_frame=${count},setpts=PTS-STARTPTS"
    local caption_count caption_index
    caption_count="$(jq -r --arg n "$name" '.shots[] | select(.name == $n) | (.captions // []) | length' "$SHOTS_FILE")"
    for (( caption_index = 0; caption_index < caption_count; caption_index++ )); do
        local caption_at caption_until caption_size
        caption_at="$(jq -r --arg n "$name" --argjson i "$caption_index" '.shots[] | select(.name == $n) | .captions[$i].at' "$SHOTS_FILE")"
        caption_until="$(jq -r --arg n "$name" --argjson i "$caption_index" '.shots[] | select(.name == $n) | .captions[$i].until' "$SHOTS_FILE")"
        caption_size="$(jq -r --arg n "$name" --argjson i "$caption_index" '.shots[] | select(.name == $n) | .captions[$i].font_size' "$SHOTS_FILE")"
        jq -j --arg n "$name" --argjson i "$caption_index" '.shots[] | select(.name == $n) | .captions[$i].text' "$SHOTS_FILE" > "$dir/caption-${caption_index}.txt"
        # Faded in and out over 0.4s, low and centred: the HUD's bars sit lower left and the
        # clock top centre, and the middle of the frame is what the shot is about.
        video_filters+=",drawtext=fontfile='${FONT_FILE}':textfile='${dir}/caption-${caption_index}.txt':"
        video_filters+="fontsize=${caption_size}:fontcolor=${INK}:box=1:boxcolor=${PAPER}@0.86:boxborderw=14:"
        video_filters+="x=(w-text_w)/2:y=h*0.84:alpha='min(1\\,max(0\\,min((t-${caption_at})/0.4\\,(${caption_until}-t)/0.4)))'"
    done
    if jq -e --arg n "$name" '.shots[] | select(.name == $n) | .ending != null' "$SHOTS_FILE" >/dev/null; then
        local ending_at line_size url_size
        ending_at="$(shot_nested_field "$name" ending at)"
        line_size="$(shot_nested_field "$name" ending line_font_size)"
        url_size="$(shot_nested_field "$name" ending url_font_size)"
        shot_nested_field "$name" ending line > "$dir/ending-line.txt"
        shot_nested_field "$name" ending url > "$dir/ending-url.txt"
        video_filters+=",drawtext=fontfile='${FONT_FILE}':textfile='${dir}/ending-line.txt':"
        video_filters+="fontsize=${line_size}:fontcolor=${INK}:box=1:boxcolor=${PAPER}@0.82:boxborderw=16:"
        video_filters+="x=(w-text_w)/2:y=h*0.075:alpha='min(1\\,max(0\\,(t-${ending_at})/0.45))'"
        video_filters+=",drawtext=fontfile='${FONT_FILE}':textfile='${dir}/ending-url.txt':"
        video_filters+="fontsize=${url_size}:fontcolor=${INK}:box=1:boxcolor=${PAPER}@0.82:boxborderw=11:"
        video_filters+="x=(w-text_w)/2:y=h*0.165:alpha='min(1\\,max(0\\,(t-${ending_at})/0.45))'"
    fi
    video_filters+=",fade=t=in:st=0:d=${fade_in},fade=t=out:st=${out_start}:d=${fade_out}"
    local video_graph="[0:v]${video_filters},format=yuv420p[v];"
    if awk -v g="$gap" 'BEGIN { exit !(g > 0) }'; then
        # A separate finite black source keeps the gap in the video timeline. `tpad` after
        # `trim=end_frame` is silently cut back to the image sequence's input duration by ffmpeg's
        # output sync, even while the padded audio retains it.
        video_graph="color=c=black:s=${WIDTH}x${HEIGHT}:r=${FPS}:d=${gap}[gapv];\
[0:v]${video_filters}[shotv];[gapv][shotv]concat=n=2:v=1:a=0,format=yuv420p[v];"
    fi
    ffmpeg -hide_banner -loglevel error -y \
        -framerate "$FPS" -start_number "$start" -i "$dir/frame%08d.png" "${audio[@]}" \
        -filter_complex "\
${video_graph}\
[1:a]atrim=start=${in}:duration=${length},asetpts=PTS-STARTPTS,aformat=sample_rates=48000:channel_layouts=stereo,\
afade=t=in:st=0:d=${fade_in},afade=t=out:st=${out_start}:d=${fade_out},\
adelay=${gap_ms}:all=1,apad,atrim=duration=${total}[a]" \
        -map "[v]" -map "[a]" -r "$FPS" -c:v libx264 -preset veryfast -crf 12 \
        -c:a pcm_s16le "$out"
}

# Produces a warm paper-and-ink editorial card from the checked-in text. The resolved font and its
