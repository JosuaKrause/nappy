check_shot() {
    local name="$1" a="$WORK/check-a" b="$WORK/check-b"
    local evidence="$OUT_DIR/checks/$name/$MODE"
    render_frames "$name" "$a" || return 1
    movie_evidence "$a" "$evidence/a" "$FPS" ordinary || return 1
    cp "$evidence/a/frames.sha256" "$WORK/hash-a"
    if [[ "$TARGET" == all ]]; then
        encode_shot "$name" "$a" "$WORK/editor-a-${name}.mkv" || return 1
    fi
    local audio_a=""
    [[ -f "$a/frame.wav" ]] && audio_a="$(shasum -a 1 < "$a/frame.wav")"
    rm -rf "$a"
    if [[ "$MODE" == check-load ]]; then
        awk 'BEGIN { x=1; while (1) { x=(x+1)%1000003 } }' >/dev/null &
        LOAD_PID=$!
    fi
    if ! render_frames "$name" "$b"; then
        [[ -z "$LOAD_PID" ]] || kill "$LOAD_PID" 2>/dev/null || true
        LOAD_PID=""; return 1
    fi
    [[ -z "$LOAD_PID" ]] || kill "$LOAD_PID" 2>/dev/null || true
    LOAD_PID=""
    movie_evidence "$b" "$evidence/b" "$FPS" "$MODE" || return 1
    cp "$evidence/b/frames.sha256" "$WORK/hash-b"
    if [[ "$TARGET" == all ]]; then
        encode_shot "$name" "$b" "$WORK/editor-b-${name}.mkv" || return 1
    fi
    local audio_b=""
    [[ -f "$b/frame.wav" ]] && audio_b="$(shasum -a 1 < "$b/frame.wav")"
    rm -rf "$b"
    jq -S . "$evidence/a/manifest.json" > "$WORK/manifest-a"
    jq -S . "$evidence/b/manifest.json" > "$WORK/manifest-b"
    local simulation_match=true
    if ! diff -u "$WORK/manifest-a" "$WORK/manifest-b" > "$evidence/manifest.diff"; then
        simulation_match=false
        echo "check '$name': resolved setup or simulation observations differ; see $evidence/manifest.diff"
    fi
    jq -S 'del(.label)' "$evidence/a/settings.json" > "$WORK/settings-a"
    jq -S 'del(.label)' "$evidence/b/settings.json" > "$WORK/settings-b"
    local settings_match=true
    diff -u "$WORK/settings-a" "$WORK/settings-b" > "$evidence/settings.diff" || settings_match=false
    if [[ -f "$evidence/a/atlases.sha256" || -f "$evidence/b/atlases.sha256" ]]; then
        diff -u "$evidence/a/atlases.sha256" "$evidence/b/atlases.sha256" > "$evidence/atlases.diff" || settings_match=false
    fi
    local start end total differ in_cut first
    start="$(awk -v a="$(shot_field "$name" in 0.5)" -v f="$FPS" 'BEGIN { printf "%d\n", int(a * f + 0.5) }')"
    end="$(awk -v a="$(shot_field "$name" in 0.5)" -v b="$(shot_field "$name" length)" -v f="$FPS" \
        'BEGIN { printf "%d\n", int((a + b) * f + 0.5) }')"
    total="$(wc -l < "$WORK/hash-a" | tr -d ' ')"
    # Frames present in one render and not the other count as differences too.
    differ="$(diff "$WORK/hash-a" "$WORK/hash-b" | grep -E '^[<>]' | awk '{print $3}' | sort -u || true)"
    in_cut=0
    first=""
    while IFS= read -r frame; do
        [[ -z "$frame" ]] && continue
        [[ -z "$first" ]] && first="$frame"
        local n=$(( 10#$(printf '%s' "$frame" | tr -dc '0-9') ))
        if (( n >= start && n < end )); then in_cut=$(( in_cut + 1 )); fi
    done <<< "$differ"
    local n_differ
    n_differ="$(printf '%s' "$differ" | grep -c . || true)"
    local audio_note="audio identical"
    [[ "$audio_a" != "$audio_b" ]] && audio_note="audio DIFFERS"
    if [[ "$n_differ" -eq 0 ]]; then
        echo "check '$name': $total frames, every one identical; $audio_note"
    else
        echo "check '$name': $n_differ of $total frames differ ($in_cut inside the cut," \
            "frames $start-$((end - 1))); first: $first; $audio_note"
    fi
    local passed=false
    [[ "$in_cut" -eq 0 && "$audio_a" == "$audio_b" && "$simulation_match" == true && "$settings_match" == true ]] && passed=true
    jq -n --argjson passed "$passed" --argjson simulation_match "$simulation_match" \
        --argjson cut_frame_differences "$in_cut" --arg mode "$MODE" \
        --argjson settings_match "$settings_match" \
        --argjson load_workers "$([[ "$MODE" == check-load ]] && echo 1 || echo 0)" \
        --argjson audio_match "$([[ "$audio_a" == "$audio_b" ]] && echo true || echo false)" \
        '{passed:$passed,mode:$mode,simulation_match:$simulation_match,settings_match:$settings_match,
          second_render_cpu_load_workers:$load_workers,
          cut_frame_differences:$cut_frame_differences,audio_match:$audio_match}' > "$evidence/result.json"
    [[ "$passed" == true ]]
}

check_card() {
    local name="$1" a="$WORK/card-a.mkv" b="$WORK/card-b.mkv"
    local evidence="$OUT_DIR/checks/$name/$MODE"
    mkdir -p "$evidence"
    encode_card "$name" "$a" || return 1
    [[ "$TARGET" != all ]] || cp "$a" "$WORK/editor-a-${name}.mkv"
    ffmpeg -hide_banner -loglevel error -y -i "$a" -map 0:v -f framehash -hash sha256 "$WORK/card-a.frames"
    ffmpeg -hide_banner -loglevel error -y -i "$a" -map 0:a -f hash -hash sha256 "$WORK/card-a.audio"
    if [[ "$MODE" == check-load ]]; then
        awk 'BEGIN { x=1; while (1) { x=(x+1)%1000003 } }' >/dev/null &
        LOAD_PID=$!
    fi
    encode_card "$name" "$b" || return 1
    [[ "$TARGET" != all ]] || cp "$b" "$WORK/editor-b-${name}.mkv"
    [[ -z "$LOAD_PID" ]] || kill "$LOAD_PID" 2>/dev/null || true
    LOAD_PID=""
    ffmpeg -hide_banner -loglevel error -y -i "$b" -map 0:v -f framehash -hash sha256 "$WORK/card-b.frames"
    ffmpeg -hide_banner -loglevel error -y -i "$b" -map 0:a -f hash -hash sha256 "$WORK/card-b.audio"
    local passed=false
    if diff -u "$WORK/card-a.frames" "$WORK/card-b.frames" > "$evidence/frames.diff" \
        && diff -u "$WORK/card-a.audio" "$WORK/card-b.audio" > "$evidence/audio.diff"; then
        passed=true
    fi
    local asset asset_sha=""
    asset="$(shot_nested_field "$name" card asset)"
    [[ "$asset" == null ]] || asset_sha="$(shasum -a 256 < "$PROJECT_DIR/$asset" | awk '{print $1}')"
    jq -n --argjson passed "$passed" --arg mode "$MODE" --arg asset "$asset" \
        --arg asset_sha256 "$asset_sha" \
        --arg font "$FONT_FILE" --arg font_sha256 "$(shasum -a 256 < "$FONT_FILE" | awk '{print $1}')" \
        '{passed:$passed,mode:$mode,kind:"editorial card",font:$font,font_sha256:$font_sha256,
          asset:(if $asset == "null" then null else $asset end),asset_sha256:$asset_sha256}' \
        > "$evidence/result.json"
    if [[ "$passed" == true ]]; then
        echo "check '$name': editorial card video and silence are identical"
    else
        echo "check '$name': editorial card differs; see $evidence" >&2
    fi
    [[ "$passed" == true ]]
}

check_editor() {
    local evidence="$OUT_DIR/checks/editor/$MODE"
    local saved_output="${OUTPUT:-}" a_parts=() b_parts=() name
    mkdir -p "$evidence"
    for name in "${SHOT_NAMES[@]}"; do
        a_parts+=("$WORK/editor-a-${name}.mkv")
        b_parts+=("$WORK/editor-b-${name}.mkv")
    done
    OUTPUT="$WORK/editor-a.mp4"
    join_shots true "${a_parts[@]}" || return 1
    OUTPUT="$WORK/editor-b.mp4"
    join_shots true "${b_parts[@]}" || return 1
    OUTPUT="$saved_output"
    ffmpeg -hide_banner -loglevel error -y -i "$WORK/editor-a.mp4" -map 0:v \
        -f framehash -hash sha256 "$WORK/editor-a.frames"
    ffmpeg -hide_banner -loglevel error -y -i "$WORK/editor-a.mp4" -map 0:a \
        -f hash -hash sha256 "$WORK/editor-a.audio"
    ffmpeg -hide_banner -loglevel error -y -i "$WORK/editor-b.mp4" -map 0:v \
        -f framehash -hash sha256 "$WORK/editor-b.frames"
    ffmpeg -hide_banner -loglevel error -y -i "$WORK/editor-b.mp4" -map 0:a \
        -f hash -hash sha256 "$WORK/editor-b.audio"
    local video_match=false audio_match=false passed=false
    diff -u "$WORK/editor-a.frames" "$WORK/editor-b.frames" > "$evidence/frames.diff" && video_match=true
    diff -u "$WORK/editor-a.audio" "$WORK/editor-b.audio" > "$evidence/audio.diff" && audio_match=true
    [[ "$video_match" == true && "$audio_match" == true ]] && passed=true
    jq -n --argjson passed "$passed" --argjson video_match "$video_match" \
        --argjson audio_match "$audio_match" --arg mode "$MODE" \
        '{passed:$passed,mode:$mode,scope:"complete editorial composition",
          decoded_video_match:$video_match,decoded_audio_match:$audio_match}' > "$evidence/result.json"
    if [[ "$passed" == true ]]; then
        echo "check 'editor': ending overlays, score and final mix are identical"
    else
        echo "check 'editor': final composition differs; see $evidence" >&2
    fi
    [[ "$passed" == true ]]
}

