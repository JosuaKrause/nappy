#!/usr/bin/env bash
# Render the trailer from the game itself, frame-locked, from the checked-in shot list.
#
#   tools/trailer.sh                  # every shot, joined -> build/trailer/trailer.mp4
#   tools/trailer.sh --shot choice    # one shot alone     -> build/trailer/shot-choice.mp4
#   tools/trailer.sh --check choice   # render it twice and compare every frame's hash
#   tools/trailer.sh --check all      # the same for every shot
#   tools/trailer.sh --list           # print the shot list and render nothing
#
# PLAYTEST-139: "we can use recordings from a frame locked game. the trailer will be a set of
# paths in pre determined seeds with fixed events so we can reproduce it easily" · "we need to be
# careful not to directly check in either the images or the video so it should be possible to
# run by me and I can generate the video myself. so the setting scripts need to produce the same
# output every time."
#
# Each shot in tools/trailer/shots.json is one Godot launch through its own movie writer
# (`--write-movie <tmp>/frame.png --fixed-fps <fps>`): the game runs frame-locked -- every frame
# advances the clock by exactly 1/fps however long it takes to draw and save -- and writes one PNG
# per frame plus `frame.wav`, the game's own audio mixed at the same clock. The shot's cut is
# taken out of those frames, faded in and out of black and encoded, and the frames are deleted
# before the next shot starts. Editorial cards, end copy and the original oscillator score are
# generated by ffmpeg from the same checked-in shot list; captured game audio stays audible under
# that score. The shots are then joined into one H.264/AAC file. Everything this
# writes is under build/ (gitignored) or a temporary directory it removes, and it fails, naming the
# paths, if the working tree's own status changed while it ran.
#
# The window opens at the game's own resolution (project.godot's viewport size), takes no focus
# and hears no stray key: the movie writer (`--write-movie`) makes DevFlags.recording() true, which
# is itself one of is_rig()'s conditions, so the game's M195 lockdown applies without any dev flag
# of its own, and the same focus guard tools/shot.sh uses hands focus straight back. Every shot also
# carries `--player-view`, so the frame is the release build's own HUD with the debug readout off
# rather than a rig's, and `--no-focus-pause`, since a window that never has real OS focus in the
# first place would otherwise open the pause screen on its own first frame and every frame shows
# that instead of the day it was sent to render. A shot is killed from outside if it outlives the
# movie writer's own deadline
# (see rig_kill_after_movie_seconds in tools/lib_dev_flags.sh).
set -euo pipefail

GODOT="${GODOT:-/Applications/Godot.app/Contents/MacOS/Godot}"
PROJECT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SHOTS_FILE="$PROJECT_DIR/tools/trailer/shots.json"
OUT_DIR="$PROJECT_DIR/build/trailer"
# shellcheck source=tools/lib_dev_flags.sh
source "$PROJECT_DIR/tools/lib_dev_flags.sh"
# shellcheck source=tools/lib_movie_evidence.sh
source "$PROJECT_DIR/tools/lib_movie_evidence.sh"
# shellcheck source=tools/lib_disk_headroom.sh
source "$PROJECT_DIR/tools/lib_disk_headroom.sh"

usage() {
    cat <<EOF
usage: tools/trailer.sh [--help|-h] [--list | --validate | --shot NAME | --check NAME|all | --check-load NAME|all]

Renders the trailer from tools/trailer/shots.json: gameplay shots through Godot's movie writer,
frame-locked, at the game's own resolution with its audio; editorial cards and the deterministic
oscillator score through ffmpeg; then fades, mixes, joins and encodes them. Frames are deleted as
soon as each shot is encoded. Output goes to build/trailer/ (gitignored).

  (no flag)        render every shot and join them into build/trailer/trailer.mp4
  --shot NAME      render one shot alone into build/trailer/shot-NAME.mp4
  --check NAME     render the shot twice and compare every frame's hash; exits non-zero on a
                   difference inside the shot's cut
  --check all      the same for every shot in the list
  --check-load NAME|all  compare an ordinary render with one under a CPU load worker
  --validate       headlessly validate every recipe; never open a recording window
  --list           print the shot list (name, kind, source, length, gap); render nothing

Disk: frames stay on disk until each shot is encoded, so this refuses to start unless the volume
holding \$TMPDIR has the record-second estimate (tools/lib_disk_headroom.sh) free for every game
second of the shots asked for (an upper bound, as only one shot's frames exist at a time), and warns
when that leaves less than the reserve. A stale atlas repair is checked the same way.

Checks retain hashes, manifests and settings in build/trailer/checks/. Simulation observations
and audio must match too; editorial cards compare decoded frame and silence hashes. Equality applies only to
the recorded engine, assets, ffmpeg/font, and settings named by the retained manifests.

  tools/trailer.sh --shot choice

Opens a window for each gameplay shot. Needs jq, ffmpeg and fc-match on PATH, and Godot 4.7 at \$GODOT.
EOF
}

MODE="all"
TARGET=""
while [[ $# -gt 0 ]]; do
    case "$1" in
        --help|-h) usage; exit 0 ;;
        --list|--validate)
            [[ "$MODE" == "all" ]] || { echo "$1 cannot be combined with --$MODE" >&2; usage >&2; exit 1; }
            MODE="${1#--}"; shift ;;
        --shot|--check|--check-load)
            [[ "$MODE" == "all" ]] || { echo "$1 cannot be combined with --$MODE" >&2; usage >&2; exit 1; }
            if [[ $# -lt 2 || "$2" == --* ]]; then
                echo "$1 is missing its shot name" >&2; echo >&2; usage >&2; exit 1
            fi
            MODE="${1#--}"; TARGET="$2"; shift 2 ;;
        *)
            echo "unrecognized argument: $1" >&2; echo >&2; usage >&2; exit 1 ;;
    esac
done

for tool in jq; do
    if ! command -v "$tool" >/dev/null 2>&1; then
        echo "trailer.sh: $tool not found on PATH" >&2
        exit 127
    fi
done
if [[ ! -f "$SHOTS_FILE" ]]; then
    echo "trailer.sh: no shot list at ${SHOTS_FILE#"$PROJECT_DIR"/}" >&2
    exit 1
fi

# ------------------------------------------------------------------- the shot list, checked ---
# Every shot is checked before any window opens: the fields a shot must carry, the dev flags it
# forwards (against the game's own DEV_FLAG_TABLE, the same way run.sh and shot.sh check theirs),
# and the whole cut against the list's own `max_seconds` -- PLAYTEST-139's "30s should be max".
schema_errors="$(jq -r '
    def num: type == "number";
    (if (keys - ["fps","max_seconds","fade","style","score","shots"] | length) == 0
        then empty else "unknown top-level field" end),
    (if (.fps | num) and .fps > 0 and .fps == (.fps | floor) then empty
        else "fps must be a positive integer" end),
    (if (.max_seconds | num) and .max_seconds > 0 and .max_seconds <= 30 then empty
        else "max_seconds must be positive and at most 30" end),
    (if (.shots | type) == "array" and (.shots | length) > 0 then empty
        else "shots must be a non-empty array" end),
    (if (.style | type) == "object" and
        (.style | keys - ["font_family","card_background","paper","ink","accent"] | length) == 0 and
        all([.style.font_family,.style.card_background,.style.paper,.style.ink,.style.accent][];
            type == "string" and length > 0)
        then empty else "style must name the font and three colors" end),
    (if (.score | type) == "object" and
        (.score | keys - ["game_gain","notes"] | length) == 0 and
        (.score.game_gain | num) and .score.game_gain >= 0 and .score.game_gain <= 1 and
        (.score.notes | type) == "array" and (.score.notes | length) > 0 and
        all(.score.notes[];
            (keys - ["at","duration","frequency","gain"] | length) == 0 and
            (.at | num) and .at >= 0 and (.duration | num) and .duration > 0 and
            (.frequency | num) and .frequency > 0 and (.gain | num) and .gain > 0 and .gain <= 0.25)
        then empty else "score must contain bounded deterministic notes and a game_gain" end),
    ((.shots // [])[] |
        (.name // "?") as $n |
        (.kind // "scene") as $kind |
        (if (.name | type) == "string" and (.name | test("^[a-z0-9-]+$")) then empty
            else "a shot name must be lower-case letters, digits and dashes: \($n)" end),
        (if $kind == "scene" or $kind == "card" then empty
            else "\($n): kind must be scene or card" end),
        (if $kind == "scene" and (.recipe | type) == "string" and
                (.recipe | test("^scene-recipes/[a-z0-9-]+\\.json$")) and (.card == null)
            then empty
            elif $kind == "card" and (.recipe == null) and (.in == null) and
                (.card | type) == "object" and
                (.card | keys - ["text","font_size","subtitle","subtitle_font_size","asset"] | length) == 0 and
                (((.card.asset | type) == "string" and (.card.asset | test("^art/[a-z0-9/_-]+\\.png$")) and
                    .card.text == null and .card.font_size == null and .card.subtitle == null and
                    .card.subtitle_font_size == null) or
                 ((.card.text | type) == "string" and (.card.text | length) > 0 and
                    (.card.font_size | num) and .card.font_size > 0 and .card.asset == null and
                    ((.card.subtitle == null and .card.subtitle_font_size == null) or
                     ((.card.subtitle | type) == "string" and (.card.subtitle | length) > 0 and
                      (.card.subtitle_font_size | num) and .card.subtitle_font_size > 0))))
            then empty
            else "\($n): scene shots need a recipe; card shots need text and font_size" end),
        (if (keys - ["name","kind","recipe","card","ending","motion","length","in","gap","fade_in","fade_out"] | length) == 0
            then empty else "\($n): unknown shot field (setup and playback belong in the recipe)" end),
        (if .motion == null or (.motion | type) == "boolean" then empty
            else "\($n): motion must be true or false" end),
        (if .ending == null then empty
            elif $kind == "scene" and (.ending | type) == "object" and
                (.ending | keys - ["at","line","url","line_font_size","url_font_size"] | length) == 0 and
                (.ending.at | num) and .ending.at >= 0 and
                all([.ending.line,.ending.url][]; type == "string" and length > 0) and
                all([.ending.line_font_size,.ending.url_font_size][]; num and . > 0)
            then empty else "\($n): ending copy is malformed or belongs to a card" end),
        (if (.length | num) and .length > 0 then empty else "\($n): length must be positive" end),
        (if (.in // 0 | num) and (.in // 0) >= 0 then empty else "\($n): in must be >= 0" end),
        (if (.gap // 0 | num) and (.gap // 0) >= 0 then empty else "\($n): gap must be >= 0" end),
        (if all([(.fade_in // 0.25),(.fade_out // 0.25)][]; num and . >= 0) then empty
            else "\($n): fades must be nonnegative numbers" end)
    ),
    (if ([.shots[]?.name] | length) == ([.shots[]?.name] | unique | length) then empty
        else "two shots share a name" end)
' "$SHOTS_FILE" 2>&1)" || { echo "trailer.sh: ${SHOTS_FILE#"$PROJECT_DIR"/} is not valid JSON" >&2; exit 1; }
if [[ -n "$schema_errors" ]]; then
    echo "trailer.sh: ${SHOTS_FILE#"$PROJECT_DIR"/} is malformed:" >&2
    printf '  %s\n' "$schema_errors" >&2
    exit 1
fi

FPS="$(jq -r '.fps' "$SHOTS_FILE")"
MAX_SECONDS="$(jq -r '.max_seconds' "$SHOTS_FILE")"
DEFAULT_FADE="$(jq -r '.fade // 0.25' "$SHOTS_FILE")"
SHOT_NAMES=()
while IFS= read -r name; do SHOT_NAMES+=("$name"); done < <(jq -r '.shots[].name' "$SHOTS_FILE")

# One field of one shot, or $3 when the shot does not carry it.
shot_field() {
    jq -r --arg n "$1" --arg f "$2" --arg d "${3:-}" \
        '.shots[] | select(.name == $n) | (.[$f] // $d) | tostring' "$SHOTS_FILE"
}

shot_kind() {
    shot_field "$1" kind scene
}

shot_nested_field() {
    jq -r --arg n "$1" --arg o "$2" --arg f "$3" \
        '.shots[] | select(.name == $n) | .[$o][$f] | tostring' "$SHOTS_FILE"
}

# The recipe owns scene setup and playback; the shot only selects the capture deadline.
shot_game_flags() {
    [[ "$(shot_kind "$1")" == scene ]] || return 0
    printf '%s\n' --player-view --no-save --no-focus-pause \
        --recipe "$PROJECT_DIR/$(shot_field "$1" recipe)" --recipe-mode scripted \
        --after "$(shot_render_seconds "$1")"
}

# Run every authored assertion, even when the selected cut ends before the scene does.
shot_render_seconds() {
    local duration
    duration="$(jq -r '.playback.duration // 5' "$PROJECT_DIR/$(shot_field "$1" recipe)")"
    awk -v a="$(shot_field "$1" in 0.5)" -v b="$(shot_field "$1" length)" \
        -v duration="$duration" 'BEGIN { end=a+b; printf "%.3f\n", (end>duration ? end : duration) }'
}

total_seconds="$(jq -r '[.shots[] | (.gap // 0) + .length] | add' "$SHOTS_FILE" |
    awk '{ printf "%.2f\n", $1 }')"
if awk -v t="$total_seconds" -v m="$MAX_SECONDS" 'BEGIN { exit !(t > m + 0.0001) }'; then
    echo "trailer.sh: the shot list runs ${total_seconds}s, over its own max_seconds ($MAX_SECONDS)" >&2
    exit 1
fi
if ! jq -e --argjson total "$total_seconds" '
    all(.score.notes[]; .at + .duration <= $total) and
    all(.shots[] | select(.ending != null); .ending.at < .length)
' "$SHOTS_FILE" >/dev/null; then
    echo "trailer.sh: score notes and ending copy must finish inside the cut" >&2
    exit 1
fi

for name in "${SHOT_NAMES[@]}"; do
    [[ "$(shot_kind "$name")" == scene ]] || continue
    flags=()
    while IFS= read -r word; do flags+=("$word"); done < <(shot_game_flags "$name")
    if ! validate_dev_flags "${flags[@]}"; then
        echo "trailer.sh: shot '$name' forwards a flag the game does not know (see above)" >&2
        exit 1
    fi
done

if [[ "$MODE" == "shot" || "$MODE" == "check" || "$MODE" == "check-load" ]] && [[ "$TARGET" != "all" || "$MODE" == "shot" ]]; then
    found=""
    for name in "${SHOT_NAMES[@]}"; do [[ "$name" == "$TARGET" ]] && found=1; done
    if [[ -z "$found" ]]; then
        echo "trailer.sh: no shot named '$TARGET' in the list (${SHOT_NAMES[*]})" >&2
        exit 1
    fi
fi

if [[ "$MODE" == "list" ]]; then
    printf '%-10s %-10s %-40s %6s %5s\n' shot kind source length gap
    for name in "${SHOT_NAMES[@]}"; do
        source="$(shot_field "$name" recipe '[editorial card]')"
        printf '%-10s %-10s %-40s %6s %5s\n' "$name" "$(shot_kind "$name")" "$source" \
            "$(shot_field "$name" length)" "$(shot_field "$name" gap 0)"
    done
    echo "total ${total_seconds}s of ${MAX_SECONDS}s"
    exit 0
fi

for tool in ffmpeg fc-match; do
