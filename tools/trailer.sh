    headroom_preflight tools/trailer.sh "$WORK" \
        "render fewer shots: --shot NAME renders one, and the shot list's lengths set the rest" \
        "record-second:$render_seconds_total" || exit 1
fi

# Renders shot $1's frames and audio into directory $2 (created empty). Fails loudly if Godot
# did not quit on its own or did not write the frames the cut needs.
render_frames() {
    local name="$1" dir="$2" after kill_after flags=()
    rm -rf "$dir"; mkdir -p "$dir"
    while IFS= read -r word; do flags+=("$word"); done < <(shot_game_flags "$name")
    flags+=(--recipe-manifest "$dir/manifest.json")
    after="$(shot_render_seconds "$name")"
    kill_after="$(rig_kill_after_movie_seconds --after "$after")"
    echo "rendering '$name' (${after}s of game at ${FPS}fps)..." >&2
    local noted
    noted="$(rig_focus_note)"
    "$GODOT" --path "$PROJECT_DIR" --resolution "${WIDTH}x${HEIGHT}" --disable-vsync \
        --write-movie "$dir/frame.png" --fixed-fps "$FPS" \
        -- "${flags[@]}" > "$dir/godot.log" 2>&1 &
    local pid=$!
    FOCUS_WATCHER_PID="$(rig_focus_watch_start "$pid" "$noted")"
    if ! wait_or_kill "$pid" "$kill_after"; then
        rig_focus_watch_stop "$FOCUS_WATCHER_PID"; FOCUS_WATCHER_PID=""
        echo "trailer.sh: killed Godot after ${kill_after}s rendering '$name' -- it did not quit" >&2
        tail -20 "$dir/godot.log" >&2
        return 1
    fi
    rig_focus_watch_stop "$FOCUS_WATCHER_PID"; FOCUS_WATCHER_PID=""
    if [[ "$WAIT_OR_KILL_STATUS" -ne 0 ]]; then
        echo "trailer.sh: Godot exited $WAIT_OR_KILL_STATUS rendering '$name'" >&2
        tail -20 "$dir/godot.log" >&2
        return 1
    fi
    if grep -qE '^(SCRIPT )?ERROR' "$dir/godot.log"; then
        echo "trailer.sh: '$name' printed an engine error while rendering:" >&2
        grep -E -A2 '^(SCRIPT )?ERROR' "$dir/godot.log" | head -20 >&2
        return 1
    fi
    movie_manifest_check "$dir/manifest.json" true || return 1
    movie_playback_check "$dir/manifest.json" || return 1
    local need last
    need="$(awk -v a="$(shot_field "$name" in 0.5)" -v b="$(shot_field "$name" length)" \
        -v f="$FPS" 'BEGIN { printf "%d\n", int((a + b) * f + 0.5) }')"
    last="$(printf '%s/frame%08d.png' "$dir" "$((need - 1))")"
    if [[ ! -f "$last" ]]; then
        echo "trailer.sh: '$name' wrote too few frames (no $(basename "$last"))" >&2
        return 1
    fi
    visible_motion_check "$name" "$dir"
}

# A manifest proves that the recipe advanced; this proves that the selected pixels did too. The
# half-second ceiling permits a deliberate held pose while rejecting the stale viewport texture a
# covered macOS movie-writer window otherwise repeats for the rest of a live scene.
visible_motion_check() {
    local name="$1" dir="$2"
    [[ "$(shot_field "$name" motion false)" == true ]] || return 0
    local start count end frame file hash previous="" run=0 longest=0
    start="$(awk -v a="$(shot_field "$name" in 0.5)" -v f="$FPS" \
        'BEGIN { printf "%d\n", int(a * f + 0.5) }')"
    count="$(awk -v a="$(shot_field "$name" length)" -v f="$FPS" \
        'BEGIN { printf "%d\n", int(a * f + 0.5) }')"
    end=$(( start + count ))
    for (( frame=start; frame<end; frame++ )); do
        file="$(printf '%s/frame%08d.png' "$dir" "$frame")"
        hash="$(shasum -a 256 < "$file" | awk '{print $1}')"
        if [[ "$hash" == "$previous" ]]; then
            run=$(( run + 1 ))
        else
            run=1
            previous="$hash"
        fi
        (( run > longest )) && longest="$run"
    done
    if (( longest > FPS / 2 )); then
        echo "trailer.sh: '$name' has $longest consecutive identical selected frames; its visible motion froze" >&2
        return 1
    fi
}

# Encodes shot $1's cut out of the frames in $2 into $3: trimmed to [in, in + length], faded in
# from and out to black, preceded by `gap` seconds of black and silence.
encode_shot() {
    local name="$1" dir="$2" out="$3"
    local in length gap fade_in fade_out start count
    in="$(shot_field "$name" in 0.5)"
    length="$(shot_field "$name" length)"
    gap="$(shot_field "$name" gap 0)"
    fade_in="$(shot_field "$name" fade_in "$DEFAULT_FADE")"
    fade_out="$(shot_field "$name" fade_out "$DEFAULT_FADE")"
    start="$(awk -v a="$in" -v f="$FPS" 'BEGIN { printf "%d\n", int(a * f + 0.5) }')"
    count="$(awk -v a="$length" -v f="$FPS" 'BEGIN { printf "%d\n", int(a * f + 0.5) }')"
    local out_start total
    out_start="$(awk -v l="$length" -v o="$fade_out" 'BEGIN { printf "%.4f\n", l - o }')"
    total="$(awk -v l="$length" -v g="$gap" 'BEGIN { printf "%.4f\n", l + g }')"
    local audio=(-f lavfi -i "anullsrc=r=48000:cl=stereo")
    [[ -f "$dir/frame.wav" ]] && audio=(-i "$dir/frame.wav")
    local gap_ms
    gap_ms="$(awk -v g="$gap" 'BEGIN { printf "%d\n", int(g * 1000 + 0.5) }')"
    local video_filters="trim=end_frame=${count},setpts=PTS-STARTPTS"
    if jq -e --arg n "$name" '.shots[] | select(.name == $n) | .ending != null' "$SHOTS_FILE" >/dev/null; then
        local ending_at line_size url_size
        ending_at="$(shot_nested_field "$name" ending at)"
        line_size="$(shot_nested_field "$name" ending line_font_size)"
        url_size="$(shot_nested_field "$name" ending url_font_size)"
        shot_nested_field "$name" ending line > "$dir/ending-line.txt"
        shot_nested_field "$name" ending url > "$dir/ending-url.txt"
        video_filters+=",drawtext=fontfile='${FONT_FILE}':textfile='${dir}/ending-line.txt':"
        video_filters+="fontsize=${line_size}:fontcolor=${INK}:box=1:boxcolor=${PAPER}@0.82:boxborderw=16:"
        video_filters+="x=(w-text_w)/2:y=h*0.075:alpha='min(1\\,max(0\\,(t-${ending_at})/0.45))'"
        video_filters+=",drawtext=fontfile='${FONT_FILE}':textfile='${dir}/ending-url.txt':"
        video_filters+="fontsize=${url_size}:fontcolor=${INK}:box=1:boxcolor=${PAPER}@0.82:boxborderw=11:"
        video_filters+="x=(w-text_w)/2:y=h*0.165:alpha='min(1\\,max(0\\,(t-${ending_at})/0.45))'"
    fi
    video_filters+=",fade=t=in:st=0:d=${fade_in},fade=t=out:st=${out_start}:d=${fade_out}"
    local video_graph="[0:v]${video_filters},format=yuv420p[v];"
    if awk -v g="$gap" 'BEGIN { exit !(g > 0) }'; then
        # A separate finite black source keeps the gap in the video timeline. `tpad` after
        # `trim=end_frame` is silently cut back to the image sequence's input duration by ffmpeg's
        # output sync, even while the padded audio retains it.
        video_graph="color=c=black:s=${WIDTH}x${HEIGHT}:r=${FPS}:d=${gap}[gapv];\
[0:v]${video_filters}[shotv];[gapv][shotv]concat=n=2:v=1:a=0,format=yuv420p[v];"
    fi
    ffmpeg -hide_banner -loglevel error -y \
        -framerate "$FPS" -start_number "$start" -i "$dir/frame%08d.png" "${audio[@]}" \
        -filter_complex "\
${video_graph}\
[1:a]atrim=start=${in}:duration=${length},asetpts=PTS-STARTPTS,aformat=sample_rates=48000:channel_layouts=stereo,\
afade=t=in:st=0:d=${fade_in},afade=t=out:st=${out_start}:d=${fade_out},\
adelay=${gap_ms}:all=1,apad,atrim=duration=${total}[a]" \
        -map "[v]" -map "[a]" -r "$FPS" -c:v libx264 -preset veryfast -crf 12 \
        -c:a pcm_s16le "$out"
}

# Produces a warm paper-and-ink editorial card from the checked-in text. The resolved font and its
# hash are retained beside the final trailer so a different host font cannot be mistaken for the
# same edit.
encode_card() {
    local name="$1" out="$2"
    local length gap fade_in fade_out out_start total gap_ms asset
    length="$(shot_field "$name" length)"
    gap="$(shot_field "$name" gap 0)"
    fade_in="$(shot_field "$name" fade_in "$DEFAULT_FADE")"
    fade_out="$(shot_field "$name" fade_out "$DEFAULT_FADE")"
    out_start="$(awk -v l="$length" -v o="$fade_out" 'BEGIN { printf "%.4f\n", l - o }')"
    total="$(awk -v l="$length" -v g="$gap" 'BEGIN { printf "%.4f\n", l + g }')"
    gap_ms="$(awk -v g="$gap" 'BEGIN { printf "%d\n", int(g * 1000 + 0.5) }')"
    asset="$(shot_nested_field "$name" card asset)"
    if [[ "$asset" != null ]]; then
        ffmpeg -hide_banner -loglevel error -y \
            -f lavfi -i "color=c=${CARD_BACKGROUND}:s=${WIDTH}x${HEIGHT}:r=${FPS}:d=${length}" \
            -f lavfi -i "anullsrc=r=48000:cl=stereo" \
            -loop 1 -framerate "$FPS" -t "$length" -i "$PROJECT_DIR/$asset" \
            -filter_complex "\
[0:v][2:v]overlay=x=(W-w)/2:y=(H-h)/2:shortest=1:format=auto,\
fade=t=in:st=0:d=${fade_in},fade=t=out:st=${out_start}:d=${fade_out},\
tpad=start_duration=${gap}:color=black,format=yuv420p[v];\
[1:a]atrim=duration=${length},asetpts=PTS-STARTPTS,afade=t=in:st=0:d=${fade_in},\
afade=t=out:st=${out_start}:d=${fade_out},adelay=${gap_ms}:all=1,apad,atrim=duration=${total}[a]" \
            -map "[v]" -map "[a]" -r "$FPS" -c:v libx264 -preset veryfast -crf 12 \
            -c:a pcm_s16le "$out"
        return
    fi
    local font_size subtitle subtitle_size text_file subtitle_file
    font_size="$(shot_nested_field "$name" card font_size)"
    subtitle="$(shot_nested_field "$name" card subtitle)"
    subtitle_size="$(shot_nested_field "$name" card subtitle_font_size)"
    text_file="$WORK/card-${name}.txt"
    subtitle_file="$WORK/card-${name}-subtitle.txt"
    shot_nested_field "$name" card text > "$text_file"
    [[ "$subtitle" == null ]] || printf '%s\n' "$subtitle" > "$subtitle_file"
    local card_filters="drawtext=fontfile='${FONT_FILE}':textfile='${text_file}':"
    card_filters+="fontsize=${font_size}:fontcolor=${PAPER}:x=(w-text_w)/2:y=h*0.29"
    if [[ "$subtitle" != null ]]; then
        card_filters+=",drawtext=fontfile='${FONT_FILE}':textfile='${subtitle_file}':"
        card_filters+="fontsize=${subtitle_size}:fontcolor=${PAPER}@0.86:x=(w-text_w)/2:y=h*0.63"
    fi
    ffmpeg -hide_banner -loglevel error -y \
        -f lavfi -i "color=c=${CARD_BACKGROUND}:s=${WIDTH}x${HEIGHT}:r=${FPS}:d=${length}" \
        -f lavfi -i "anullsrc=r=48000:cl=stereo" \
        -filter_complex "\
[0:v]${card_filters},fade=t=in:st=0:d=${fade_in},fade=t=out:st=${out_start}:d=${fade_out},\
tpad=start_duration=${gap}:color=black,format=yuv420p[v];\
[1:a]atrim=duration=${length},asetpts=PTS-STARTPTS,afade=t=in:st=0:d=${fade_in},\
afade=t=out:st=${out_start}:d=${fade_out},adelay=${gap_ms}:all=1,apad,atrim=duration=${total}[a]" \
        -map "[v]" -map "[a]" -r "$FPS" -c:v libx264 -preset veryfast -crf 12 \
        -c:a pcm_s16le "$out"
}

# Joins the encoded shots named after $1 into the final file $OUTPUT. The full cut mixes the
# deterministic score under captured game audio; isolated --shot renders retain only their own
# game audio so a scene can be inspected without music from another point in the timeline.
join_shots() {
    local include_score="$1"
    shift
    local inputs=() streams="" i=0
    for f in "$@"; do
        inputs+=(-i "$f")
        streams+="[$i:v][$i:a]"
        i=$(( i + 1 ))
    done
    mkdir -p "$(dirname "$OUTPUT")"
    if [[ "$include_score" == true ]]; then
        local score_expression game_gain score_index
        score_expression="$(jq -r '[.score.notes[] |
            "if(between(t\\,\(.at)\\,\(.at + .duration))\\,\(.gain)*sin(2*PI*\(.frequency)*(t-\(.at)))*pow(sin(PI*(t-\(.at))/\(.duration))\\,2)\\,0)"
            ] | join("+")' "$SHOTS_FILE")"
        game_gain="$(jq -r '.score.game_gain' "$SHOTS_FILE")"
        score_index="$i"
        inputs+=(-f lavfi -i "aevalsrc=exprs='${score_expression}|${score_expression}':s=48000:d=${total_seconds}:c=stereo")
        ffmpeg -hide_banner -loglevel error -y "${inputs[@]}" \
            -filter_complex "${streams}concat=n=${i}:v=1:a=1[joinedv][gamea];\
[gamea]volume=${game_gain}[gamebed];[${score_index}:a]aformat=sample_rates=48000:channel_layouts=stereo[score];\
[gamebed][score]amix=inputs=2:duration=first:normalize=0,alimiter=limit=0.92[a]" \
            -map "[joinedv]" -map "[a]" -r "$FPS" -c:v libx264 -preset slow -crf 18 -pix_fmt yuv420p \
            -c:a aac -b:a 192k -movflags +faststart "$OUTPUT"
    else
        ffmpeg -hide_banner -loglevel error -y "${inputs[@]}" \
            -filter_complex "${streams}concat=n=${i}:v=1:a=1[v][a]" \
            -map "[v]" -map "[a]" -r "$FPS" -c:v libx264 -preset slow -crf 18 -pix_fmt yuv420p \
            -c:a aac -b:a 192k -movflags +faststart "$OUTPUT"
    fi
}

check_shot() {
    local name="$1" a="$WORK/check-a" b="$WORK/check-b"
    local evidence="$OUT_DIR/checks/$name/$MODE"
    render_frames "$name" "$a" || return 1
    movie_evidence "$a" "$evidence/a" "$FPS" ordinary || return 1
    cp "$evidence/a/frames.sha256" "$WORK/hash-a"
    if [[ "$TARGET" == all ]]; then
        encode_shot "$name" "$a" "$WORK/editor-a-${name}.mkv" || return 1
    fi
    local audio_a=""
    [[ -f "$a/frame.wav" ]] && audio_a="$(shasum -a 1 < "$a/frame.wav")"
    rm -rf "$a"
    if [[ "$MODE" == check-load ]]; then
        awk 'BEGIN { x=1; while (1) { x=(x+1)%1000003 } }' >/dev/null &
        LOAD_PID=$!
    fi
    if ! render_frames "$name" "$b"; then
        [[ -z "$LOAD_PID" ]] || kill "$LOAD_PID" 2>/dev/null || true
        LOAD_PID=""; return 1
    fi
    [[ -z "$LOAD_PID" ]] || kill "$LOAD_PID" 2>/dev/null || true
    LOAD_PID=""
    movie_evidence "$b" "$evidence/b" "$FPS" "$MODE" || return 1
    cp "$evidence/b/frames.sha256" "$WORK/hash-b"
    if [[ "$TARGET" == all ]]; then
        encode_shot "$name" "$b" "$WORK/editor-b-${name}.mkv" || return 1
    fi
    local audio_b=""
    [[ -f "$b/frame.wav" ]] && audio_b="$(shasum -a 1 < "$b/frame.wav")"
    rm -rf "$b"
    jq -S . "$evidence/a/manifest.json" > "$WORK/manifest-a"
    jq -S . "$evidence/b/manifest.json" > "$WORK/manifest-b"
    local simulation_match=true
    if ! diff -u "$WORK/manifest-a" "$WORK/manifest-b" > "$evidence/manifest.diff"; then
        simulation_match=false
        echo "check '$name': resolved setup or simulation observations differ; see $evidence/manifest.diff"
    fi
    jq -S 'del(.label)' "$evidence/a/settings.json" > "$WORK/settings-a"
    jq -S 'del(.label)' "$evidence/b/settings.json" > "$WORK/settings-b"
    local settings_match=true
    diff -u "$WORK/settings-a" "$WORK/settings-b" > "$evidence/settings.diff" || settings_match=false
    if [[ -f "$evidence/a/atlases.sha256" || -f "$evidence/b/atlases.sha256" ]]; then
        diff -u "$evidence/a/atlases.sha256" "$evidence/b/atlases.sha256" > "$evidence/atlases.diff" || settings_match=false
    fi
    local start end total differ in_cut first
    start="$(awk -v a="$(shot_field "$name" in 0.5)" -v f="$FPS" 'BEGIN { printf "%d\n", int(a * f + 0.5) }')"
    end="$(awk -v a="$(shot_field "$name" in 0.5)" -v b="$(shot_field "$name" length)" -v f="$FPS" \
        'BEGIN { printf "%d\n", int((a + b) * f + 0.5) }')"
    total="$(wc -l < "$WORK/hash-a" | tr -d ' ')"
    # Frames present in one render and not the other count as differences too.
    differ="$(diff "$WORK/hash-a" "$WORK/hash-b" | grep -E '^[<>]' | awk '{print $3}' | sort -u || true)"
    in_cut=0
    first=""
    while IFS= read -r frame; do
        [[ -z "$frame" ]] && continue
        [[ -z "$first" ]] && first="$frame"
        local n=$(( 10#$(printf '%s' "$frame" | tr -dc '0-9') ))
        if (( n >= start && n < end )); then in_cut=$(( in_cut + 1 )); fi
    done <<< "$differ"
    local n_differ
    n_differ="$(printf '%s' "$differ" | grep -c . || true)"
    local audio_note="audio identical"
    [[ "$audio_a" != "$audio_b" ]] && audio_note="audio DIFFERS"
    if [[ "$n_differ" -eq 0 ]]; then
        echo "check '$name': $total frames, every one identical; $audio_note"
    else
        echo "check '$name': $n_differ of $total frames differ ($in_cut inside the cut," \
            "frames $start-$((end - 1))); first: $first; $audio_note"
    fi
    local passed=false
    [[ "$in_cut" -eq 0 && "$audio_a" == "$audio_b" && "$simulation_match" == true && "$settings_match" == true ]] && passed=true
    jq -n --argjson passed "$passed" --argjson simulation_match "$simulation_match" \
        --argjson cut_frame_differences "$in_cut" --arg mode "$MODE" \
        --argjson settings_match "$settings_match" \
        --argjson load_workers "$([[ "$MODE" == check-load ]] && echo 1 || echo 0)" \
        --argjson audio_match "$([[ "$audio_a" == "$audio_b" ]] && echo true || echo false)" \
        '{passed:$passed,mode:$mode,simulation_match:$simulation_match,settings_match:$settings_match,
          second_render_cpu_load_workers:$load_workers,
          cut_frame_differences:$cut_frame_differences,audio_match:$audio_match}' > "$evidence/result.json"
    [[ "$passed" == true ]]
}

check_card() {
    local name="$1" a="$WORK/card-a.mkv" b="$WORK/card-b.mkv"
    local evidence="$OUT_DIR/checks/$name/$MODE"
    mkdir -p "$evidence"
    encode_card "$name" "$a" || return 1
    [[ "$TARGET" != all ]] || cp "$a" "$WORK/editor-a-${name}.mkv"
    ffmpeg -hide_banner -loglevel error -y -i "$a" -map 0:v -f framehash -hash sha256 "$WORK/card-a.frames"
    ffmpeg -hide_banner -loglevel error -y -i "$a" -map 0:a -f hash -hash sha256 "$WORK/card-a.audio"
    if [[ "$MODE" == check-load ]]; then
        awk 'BEGIN { x=1; while (1) { x=(x+1)%1000003 } }' >/dev/null &
        LOAD_PID=$!
    fi
    encode_card "$name" "$b" || return 1
    [[ "$TARGET" != all ]] || cp "$b" "$WORK/editor-b-${name}.mkv"
    [[ -z "$LOAD_PID" ]] || kill "$LOAD_PID" 2>/dev/null || true
    LOAD_PID=""
    ffmpeg -hide_banner -loglevel error -y -i "$b" -map 0:v -f framehash -hash sha256 "$WORK/card-b.frames"
    ffmpeg -hide_banner -loglevel error -y -i "$b" -map 0:a -f hash -hash sha256 "$WORK/card-b.audio"
    local passed=false
    if diff -u "$WORK/card-a.frames" "$WORK/card-b.frames" > "$evidence/frames.diff" \
        && diff -u "$WORK/card-a.audio" "$WORK/card-b.audio" > "$evidence/audio.diff"; then
        passed=true
    fi
    local asset asset_sha=""
    asset="$(shot_nested_field "$name" card asset)"
    [[ "$asset" == null ]] || asset_sha="$(shasum -a 256 < "$PROJECT_DIR/$asset" | awk '{print $1}')"
    jq -n --argjson passed "$passed" --arg mode "$MODE" --arg asset "$asset" \
        --arg asset_sha256 "$asset_sha" \
        --arg font "$FONT_FILE" --arg font_sha256 "$(shasum -a 256 < "$FONT_FILE" | awk '{print $1}')" \
        '{passed:$passed,mode:$mode,kind:"editorial card",font:$font,font_sha256:$font_sha256,
          asset:(if $asset == "null" then null else $asset end),asset_sha256:$asset_sha256}' \
        > "$evidence/result.json"
    if [[ "$passed" == true ]]; then
        echo "check '$name': editorial card video and silence are identical"
    else
        echo "check '$name': editorial card differs; see $evidence" >&2
    fi
    [[ "$passed" == true ]]
}

check_editor() {
    local evidence="$OUT_DIR/checks/editor/$MODE"
    local saved_output="${OUTPUT:-}" a_parts=() b_parts=() name
    mkdir -p "$evidence"
    for name in "${SHOT_NAMES[@]}"; do
        a_parts+=("$WORK/editor-a-${name}.mkv")
        b_parts+=("$WORK/editor-b-${name}.mkv")
    done
    OUTPUT="$WORK/editor-a.mp4"
    join_shots true "${a_parts[@]}" || return 1
    OUTPUT="$WORK/editor-b.mp4"
    join_shots true "${b_parts[@]}" || return 1
    OUTPUT="$saved_output"
    ffmpeg -hide_banner -loglevel error -y -i "$WORK/editor-a.mp4" -map 0:v \
        -f framehash -hash sha256 "$WORK/editor-a.frames"
    ffmpeg -hide_banner -loglevel error -y -i "$WORK/editor-a.mp4" -map 0:a \
        -f hash -hash sha256 "$WORK/editor-a.audio"
    ffmpeg -hide_banner -loglevel error -y -i "$WORK/editor-b.mp4" -map 0:v \
        -f framehash -hash sha256 "$WORK/editor-b.frames"
    ffmpeg -hide_banner -loglevel error -y -i "$WORK/editor-b.mp4" -map 0:a \
        -f hash -hash sha256 "$WORK/editor-b.audio"
    local video_match=false audio_match=false passed=false
    diff -u "$WORK/editor-a.frames" "$WORK/editor-b.frames" > "$evidence/frames.diff" && video_match=true
    diff -u "$WORK/editor-a.audio" "$WORK/editor-b.audio" > "$evidence/audio.diff" && audio_match=true
    [[ "$video_match" == true && "$audio_match" == true ]] && passed=true
    jq -n --argjson passed "$passed" --argjson video_match "$video_match" \
        --argjson audio_match "$audio_match" --arg mode "$MODE" \
        '{passed:$passed,mode:$mode,scope:"complete editorial composition",
          decoded_video_match:$video_match,decoded_audio_match:$audio_match}' > "$evidence/result.json"
    if [[ "$passed" == true ]]; then
        echo "check 'editor': ending overlays, score and final mix are identical"
    else
        echo "check 'editor': final composition differs; see $evidence" >&2
    fi
    [[ "$passed" == true ]]
}

write_editorial_settings() {
    local revision tree dirty ffmpeg_version font_sha shots_sha card_asset card_asset_sha=""
    revision="$(git -C "$PROJECT_DIR" rev-parse HEAD)"
    tree="$(git -C "$PROJECT_DIR" rev-parse HEAD^{tree})"
    dirty="$(git -C "$PROJECT_DIR" diff HEAD -- | shasum -a 256 | awk '{print $1}')"
    ffmpeg_version="$(ffmpeg -version | head -1)"
    font_sha="$(shasum -a 256 < "$FONT_FILE" | awk '{print $1}')"
    shots_sha="$(shasum -a 256 < "$SHOTS_FILE" | awk '{print $1}')"
    card_asset="$(jq -r '[.shots[].card.asset? // empty][0] // ""' "$SHOTS_FILE")"
    [[ -z "$card_asset" ]] || card_asset_sha="$(shasum -a 256 < "$PROJECT_DIR/$card_asset" | awk '{print $1}')"
    mkdir -p "$OUT_DIR"
    jq -n --arg revision "$revision" --arg tree "$tree" --arg dirty "$dirty" \
        --arg ffmpeg "$ffmpeg_version" --arg font_family "$FONT_FAMILY" --arg font "$FONT_FILE" \
        --arg font_sha256 "$font_sha" --arg shots_sha256 "$shots_sha" \
        --arg card_asset "$card_asset" --arg card_asset_sha256 "$card_asset_sha" \
        --argjson fps "$FPS" --argjson width "$WIDTH" --argjson height "$HEIGHT" \
        --argjson duration "$total_seconds" \
        '{revision:$revision,tracked_tree:$tree,working_diff_sha256:$dirty,ffmpeg:$ffmpeg,
          font_family:$font_family,font:$font,font_sha256:$font_sha256,shots_sha256:$shots_sha256,
          card_asset:$card_asset,card_asset_sha256:$card_asset_sha256,
          fps:$fps,width:$width,height:$height,duration_seconds:$duration,
          score:"deterministic oscillator notes from tools/trailer/shots.json"}' \
        > "$OUT_DIR/editorial-settings.json"
}

# Fails, naming them, if the working tree's status moved while this ran: nothing this writes may
# be something git tracks or would offer to add.
assert_tree_untouched() {
    local after
    after="$(git -C "$PROJECT_DIR" status --porcelain 2>/dev/null || true)"
    if [[ "$after" != "$TREE_BEFORE" ]]; then
        echo "trailer.sh: the working tree's status changed while rendering:" >&2
        diff <(printf '%s\n' "$TREE_BEFORE") <(printf '%s\n' "$after") >&2 || true
        return 1
    fi
}

status=0
case "$MODE" in
    check|check-load)
        targets=("$TARGET")
        [[ "$TARGET" == "all" ]] && targets=("${SHOT_NAMES[@]}")
        for name in "${targets[@]}"; do
            if [[ "$(shot_kind "$name")" == card ]]; then
                check_card "$name" || status=1
            else
                check_shot "$name" || status=1
            fi
        done
        if [[ "$TARGET" == all && "$status" -eq 0 ]]; then
            check_editor || status=1
        fi
        ;;
    shot)
        OUTPUT="$OUT_DIR/shot-$TARGET.mp4"
        if [[ "$(shot_kind "$TARGET")" == card ]]; then
            encode_card "$TARGET" "$WORK/00.mkv"
        else
            render_frames "$TARGET" "$WORK/frames"
            movie_evidence "$WORK/frames" "$OUT_DIR/evidence/$TARGET" "$FPS" "$TARGET"
            encode_shot "$TARGET" "$WORK/frames" "$WORK/00.mkv"
            rm -rf "$WORK/frames"
        fi
        join_shots false "$WORK/00.mkv"
        echo "wrote ${OUTPUT#"$PROJECT_DIR"/}"
        ;;
    all)
        OUTPUT="$OUT_DIR/trailer.mp4"
        encoded=()
        i=0
        for name in "${SHOT_NAMES[@]}"; do
            part="$(printf '%s/%02d.mkv' "$WORK" "$i")"
            if [[ "$(shot_kind "$name")" == card ]]; then
                encode_card "$name" "$part"
            else
                render_frames "$name" "$WORK/frames"
                movie_evidence "$WORK/frames" "$OUT_DIR/evidence/$name" "$FPS" "$name"
                encode_shot "$name" "$WORK/frames" "$part"
                rm -rf "$WORK/frames"
            fi
            encoded+=("$part")
            i=$(( i + 1 ))
        done
        join_shots true "${encoded[@]}"
        write_editorial_settings
        echo "wrote ${OUTPUT#"$PROJECT_DIR"/} (${total_seconds}s, ${#SHOT_NAMES[@]} shots)"
        ;;
esac
assert_tree_untouched || status=1
exit "$status"
